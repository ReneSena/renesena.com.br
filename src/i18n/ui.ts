export type UIKey = keyof (typeof ui)['pt'];

export function useT(lang: Lang) {
  return (key: UIKey) => ui[lang][key] ?? ui.pt[key];
}

/** Converte "texto [destaque]" em HTML com <em> */
export function emph(text: string) {
  return text.replace(/\[([^\]]+)\]/g, '<em class="accent-em">$1</em>');
}

export function localePath(lang: Lang, path = '/') {
  if (lang === 'pt') return path;
  return `/en${path === '/' ? '/' : path}`;
}

/** Página da trajetória completa em cada idioma */
export function journeyPath(lang: Lang) {
  return lang === 'pt' ? '/trajetoria/' : '/en/journey/';
}

